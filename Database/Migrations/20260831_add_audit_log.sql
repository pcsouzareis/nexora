CREATE TABLE IF NOT EXISTS n017 (
    cod017 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod001 BIGINT NULL REFERENCES n001(cod001) ON UPDATE CASCADE ON DELETE SET NULL,
    cod002 BIGINT NULL REFERENCES n002(cod002) ON UPDATE CASCADE ON DELETE SET NULL,
    aca017 VARCHAR(60) NOT NULL,
    ent017 VARCHAR(60) NOT NULL,
    ref017 BIGINT NULL,
    des017 TEXT NOT NULL,
    ip017 VARCHAR(45),
    cad017 TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_n017_empresa_data ON n017 (cod001, cad017 DESC);
CREATE INDEX IF NOT EXISTS ix_n017_entidade_referencia ON n017 (ent017, ref017);
CREATE INDEX IF NOT EXISTS ix_n017_empresa_usuario_data ON n017 (cod001, cod002, cad017 DESC);
CREATE INDEX IF NOT EXISTS ix_n017_empresa_acao_data ON n017 (cod001, aca017, cad017 DESC);

COMMENT ON TABLE n017 IS 'Auditoria de ações realizadas no Nexora.';
