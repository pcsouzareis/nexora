CREATE TABLE IF NOT EXISTS n019 (
    cod019 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod001 BIGINT NOT NULL REFERENCES n001(cod001) ON DELETE CASCADE,
    cod003 BIGINT NOT NULL REFERENCES n003(cod003) ON DELETE CASCADE,
    tip019 VARCHAR(30) NOT NULL,
    sts019 VARCHAR(15) NOT NULL,
    des019 TEXT NULL,
    cad019 TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_n019_canal_data
    ON n019 (cod003, cad019 DESC);

COMMENT ON TABLE n019 IS 'Histórico técnico de sincronizações, entregas e falhas das integrações.';
COMMENT ON COLUMN n019.tip019 IS 'Tipo do evento: Sincronização, Envio, Teste ou Recebimento.';
COMMENT ON COLUMN n019.sts019 IS 'Resultado do evento: Sucesso ou Falha.';
